// a) O comando if (x = 0) realiza uma ATRIBUIÇÃO, guardando o valor 0 na variável x. 
// Em C, o resultado de uma atribuição é o próprio valor atribuído. Como o valor é 0, 
// o if interpreta isso como "falso", e o bloco de código associado NÃO será executado.
// O correto para comparação é if (x == 0).

// b) Na Linguagem C, o valor numérico 0 (zero) é sempre interpretado como FALSO. 
// Qualquer valor numérico diferente de zero (como 1, -5, 3.14) é interpretado como VERDADEIRO.

// c) A instrução if (x = -5) atribui o valor -5 à variável x. Como -5 é diferente de 0, 
// a condição é avaliada como VERDADEIRA. Portanto, o bloco de código SERÁ EXECUTADO.